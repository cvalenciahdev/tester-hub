export type Language = keyof typeof translations;
export type TranslationKey = keyof typeof translations.es;

type TranslationContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
};

const TranslationContext = createContext<TranslationContextValue | null>(null);
const LANGUAGE_STORAGE_KEY = "tester-hub-language";

function subscribeToLanguageChanges(callback: () => void) {
  window.addEventListener("storage", callback);
  window.addEventListener("tester-hub-language-change", callback);
  return () => {
    window.removeEventListener("storage", callback);
    window.removeEventListener("tester-hub-language-change", callback);
  };
}

function getStoredLanguage(): Language {
  const storedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return storedLanguage === "en" || storedLanguage === "es" ? storedLanguage : "es";
}

function getServerLanguage(): Language {
  return "es";
}

export function TranslationProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(
    subscribeToLanguageChanges,
    getStoredLanguage,
    getServerLanguage,
  );

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((nextLanguage: Language) => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    window.dispatchEvent(new Event("tester-hub-language-change"));
  }, []);

  const value = useMemo<TranslationContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values = {}) => {
      const template = translations[language][key] ?? translations.es[key];
      return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
        String(values[name] ?? ""),
      );
    },
  }), [language, setLanguage]);

  return (
    <TranslationContext.Provider value={value}>
      {children}
    </TranslationContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(TranslationContext);
  if (!context) {
    throw new Error("useI18n must be used within TranslationProvider");
  }
  return context;
}

export function T({
  id,
  values,
}: {
  id: TranslationKey;
  values?: Record<string, string | number>;
}) {
  const { t } = useI18n();
  return t(id, values);
}

export function LanguageSelector() {
  const { language, setLanguage, t } = useI18n();

  return (
    <label className="language-selector">
      <span className="sr-only">{t("language.label")}</span>
      <select
        aria-label={t("language.label")}
        value={language}
        onChange={(event) =>
          setLanguage(event.target.value === "en" ? "en" : "es")
        }
      >
        <option value="es">{t("language.spanish")}</option>
        <option value="en">{t("language.english")}</option>
      </select>
    </label>
  );
}

export function TranslatedIconButton({
  label,
  values,
  className,
  disabled = false,
  children,
}: {
  label: TranslationKey;
  values?: Record<string, string | number>;
  className: string;
  disabled?: boolean;
  children: ReactNode;
}) {
  const { t } = useI18n();
  return (
    <button className={className} aria-label={t(label, values)} type="button" disabled={disabled}>
      {children}
    </button>
  );
}

export function CurrentLanguageName() {
  const { language, t } = useI18n();
  return t(language === "en" ? "language.english" : "language.spanish");
}
